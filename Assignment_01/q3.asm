DATA SEGMENT
    MSG DB 'Sum = $'
DATA ENDS

CODE SEGMENT
    ASSUME CS:CODE, DS:DATA

START:
    MOV AX, DATA
    MOV DS, AX
    MOV AL, 25H
    MOV BL, 37H
    ADD AL, BL
    MOV BL, AL
    LEA DX, MSG
    MOV AH, 09H
    INT 21H
    MOV AL, BL
    CALL DISPLAY_HEX
    MOV AH, 4CH
    INT 21H

DISPLAY_HEX PROC
    MOV AH, AL
    AND AH, 0F0H
    MOV CL, 4
    SHR AH, CL
    MOV DL, AH
    CALL HEX_TO_ASCII
    MOV AH, 02H
    INT 21H
    MOV DL, AL
    AND DL, 0FH
    CALL HEX_TO_ASCII
    MOV AH, 02H
    INT 21H
    RET
DISPLAY_HEX ENDP

HEX_TO_ASCII PROC
    CMP DL, 09H
    JBE DIGIT
    ADD DL, 07H
DIGIT:
    ADD DL, 30H
    RET
HEX_TO_ASCII ENDP

CODE ENDS
END START
